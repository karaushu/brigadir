/**
 * spec/remote-access-and-mobile#phone, spec/remote-access-and-mobile#phone-network: the `web` client class — what a phone signed in with a passkey may call on the working
 * machine. Every method of the channel table has its own decision here (the type does not build without one): `allow`,
 * `deny`, `guarded` (main keeps what a phone may not change) or a check of the arguments. A row a phone may not reach is
 * refused in main's `dispatch` after the table's validator, like `forbidden` for a computer; its events never reach it.
 *
 * The phone is for answering the agent and looking at the state (spec/remote-access-and-mobile#phone): the sidebar and tasks, the chat with every
 * interaction, a new task, changes, the pull request with comments, review and merge, files and the terminal for reading,
 * quotas and the notification settings. Not the terminal's input, the browser, the simulator, the editor with edits and
 * LSP, the crew editor, settings beyond notifications, remote access and modules (spec/remote-access-and-mobile#phone).
 */
