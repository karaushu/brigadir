/** spec/remote-access-and-mobile#phone-network: why a phone's call is refused before any handler, or null. Runs after the table's own validator. */
export function webCallRefusal(channel: string, args: readonly unknown[]): string | null {
	const row = ipcInvokeRows.get(channel);
	if (!row) return 'Invalid IPC request';
	const access = webChannels[row.method];
	if (access === 'allow' || access === 'guarded') return null;
	if (typeof access === 'function' && access(args)) return null;
	return 'Not available from a phone.';
}
/** Whether an event of this channel may reach a phone. */
export function webEventAllowed(channel: string): boolean {
	const row = ipcSubscribeRows.get(channel);
	return Boolean(row && webChannels[row.method] === 'allow');
}
/** spec/remote-access-and-mobile#phone: a phone's `settings:save` changes the notifications only; the rest stays as it is on the machine. */
export function guardPhoneSettings(incoming: AppSettings, current: AppSettings): AppSettings {
	const copy = <T>(value: T): T => JSON.parse(JSON.stringify(value)) as T;
	return { ...copy(current), notifications: copy(incoming.notifications) };
}
